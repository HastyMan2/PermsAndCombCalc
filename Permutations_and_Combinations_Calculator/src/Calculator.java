    private void btnPRActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPRActionPerformed
        double Number = Double.parseDouble(txtN.getText());
        double Position = Double.parseDouble(txtR.getText());
        
        if (Position > Number){
            txtOutput.setText("Invalid Values");
        }
        else {
            double resultPR = Math.pow(Number, Position);
            String ResPR = String.valueOf(resultPR);
            txtOutput.setText(Number + "^" + Position + "\n=" + ResPR);
        }
        
    }//GEN-LAST:event_btnPRActionPerformed

    private void btnPNRActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPNRActionPerformed
        double Number = Double.parseDouble(txtN.getText());
        double Position = Double.parseDouble(txtR.getText());
        double f1 = factorial(Number);
        double f2 = factorial(Number - Position);
        
        if (Position > Number){
            txtOutput.setText("Invalid Values");
        }
        else {
            double resultPNR = factorial(Number)/factorial(Number - Position);
            String ResPNR = String.valueOf(resultPNR);
            txtOutput.setText("Formula: n! / (n - r)!" +
                    "\n" + Number + "! / "+ 
                    "(" + Number + " - " + Position + 
                    ")!" + "\n" + f1 + " / " + f2 + "\nPNR = " + ResPNR);
        }
    }//GEN-LAST:event_btnPNRActionPerformed

    private void btnCRActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCRActionPerformed
        double Number = Double.parseDouble(txtN.getText());
        double Position = Double.parseDouble(txtR.getText());
        double f1 = factorial(Number + Position - 1);
        double f2 = factorial(Position);
        double f3 = factorial(Number - 1);
        
        if (Position > Number){
            txtOutput.setText("Invalid Values");
        }
        else {
            double resultCR = factorial(Number+Position-1) / ((factorial(Position))*(factorial(Number - 1)));
            String ResCR = String.valueOf(resultCR);
            txtOutput.setText("Formula: (n + r - 1)! / r! (n - 1)!" +
                    "\n(" + Number + " + " + Position + ")! / "+ Position +
                    "! (" + Number + " - 1" + 
                    ")!" + "\n" + f1 + " / " + f2 + "(" + Number + " - 1)" +
                     "\n" +  f1 + " / " + f2 + " * " + f3 +
                    "\nCR = " + ResCR);
        }
    }//GEN-LAST:event_btnCRActionPerformed

    private void btnCNRActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCNRActionPerformed
        double Number = Double.parseDouble(txtN.getText());
        double Position = Double.parseDouble(txtR.getText());
        double f1 = factorial(Number);
        double f2 = factorial(Position);
        double f3 = factorial(Number - Position);
        
        if (Position > Number){
            txtOutput.setText("Invalid Values");
        }
        else {
            double resultCNR = factorial(Number) / ((factorial(Position))*(factorial(Number - Position)));
            String ResCNR = String.valueOf(resultCNR);
            txtOutput.setText("Formula: n! / r! (n - r)!" +
                    "\n" + Number + "! / "+ Position +
                    "! * (" + Number + " - " + Position +
                    ")!" + "\n" + f1 + " / " + f2 + " * (" + Number + " - " + Position +
                     ")! \n" +  f1 + " / " + f2 + " * " + f3 +
                    "\nCNR = " + ResCNR);
        }
    }//GEN-LAST:event_btnCNRActionPerformed

